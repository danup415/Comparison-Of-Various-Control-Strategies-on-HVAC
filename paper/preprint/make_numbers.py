"""Generate paper/*/numbers.tex (LaTeX macros) from results/tables/*.csv.

Every number quoted in the manuscript text is a macro defined here, so the paper cannot
drift from the simulation outputs. Run after run_all.m:  python3 paper/preprint/make_numbers.py
"""
import csv, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
T = os.path.join(ROOT, 'results', 'tables')
OUT = os.path.join(HERE, 'sections', 'numbers.tex')
COPIES = [os.path.join(ROOT, 'paper', d, 'numbers.tex') for d in ('ieee', 'springer')]
KEY = {'Thermostat': 'Th', 'PID': 'Pid', 'E-MPC': 'Mpc', 'DQN': 'Dqn', 'Hybrid': 'Hyb'}
SCN = {'base': 'Base', 'heatwave': 'Heat', 'mass_low': 'MassLo', 'mass_high': 'MassHi',
       'flat_tariff': 'Flat', 'no_mismatch': 'NoMis', 'mpc_perfect': 'Perf', 'horizon6': 'HorSix',
       'horizon12': 'HorTwelve', 'rl_levels3': 'LevThree', 'rl_levels9': 'LevNine',
       'rl_noshield': 'NoShield', 'heat_perfect': 'HeatPerf', 'heat_backoff1': 'HeatBack', 'tariff_steep': 'Steep', 'tariff_msedcl': 'Msedcl', 'hyb_noPI': 'NoPI', 'hyb_nosafety': 'NoSafe', 'iaq_nofilter': 'NoFilt', 'vent_humidity': 'VentHum', 'vent_off': 'VentOff'}
alpha = lambda s: re.sub(r'[^A-Za-z]', '', s.title())


def fmt(x, d):
    v = float(x)
    s = f"{v:,.{d}f}"
    return s.replace(',', '{,}')


lines = ['% generated by make_numbers.py -- do not edit']
def mac(name, val):
    lines.append(f'\\newcommand{{\\{name}}}{{{val}}}')

# main table
with open(os.path.join(T, 'main_kpis.csv')) as f:
    rows = list(csv.DictReader(f))
base = {r['controller']: r for r in rows}
th = base['Thermostat']
spec = {'E_total': ('E', 0), 'cost': ('Cost', 0), 'Kh_total': ('Kh', 0), 'Kh_over': ('KhOver', 0),
        'Kh_under_hvac': ('KhCold', 0), 'accept_pct': ('Acc', 1), 'rmse_occ': ('Rmse', 2),
        'P_peak': ('Peak', 2), 'starts': ('Starts', 0), 'E_vrf': ('Evrf', 0), 'carbon': ('Carbon', 0)}
for r in rows:
    k = KEY[r['controller']]
    for col, (nm, d) in spec.items():
        mac(f'{nm}{k}', fmt(r[col], d))
        mac(f'{nm}{k}CI', fmt(r[col + '_ci95'], d))
    mac(f'PeakShare{k}', fmt(100 * float(r['peak_share']), 1))
    mac(f'Ms{k}', fmt(r['ctrl_ms'], 0) if r['controller'] in ('E-MPC', 'Hybrid') else '--')
    for col, nm in (('cost', 'dCost'), ('E_total', 'dE'), ('Kh_total', 'dKh')):
        rel = 100 * (float(r[col]) - float(th[col])) / float(th[col])
        mac(f'{nm}{k}', f'{rel:+.1f}'.replace('+', '+'))
        mac(f'{nm}{k}abs', f'{abs(rel):.1f}')
    mac(f'CostSave{k}', fmt(float(th['cost']) - float(r['cost']), 0))

# pairwise relative differences (A vs B, % of B)
for A_, B_ in (('Hybrid','PID'),('Hybrid','E-MPC'),('E-MPC','PID'),('DQN','PID'),('Hybrid','DQN')):
    for col, nm in (('cost','Cost'),('Kh_total','Kh'),('E_total','E')):
        rel = 100*(float(base[A_][col]) - float(base[B_][col]))/float(base[B_][col])
        mac(f'Rel{KEY[A_]}{KEY[B_]}{nm}', f'{abs(rel):.1f}')
        mac(f'Rel{KEY[A_]}{KEY[B_]}{nm}Signed', f'{rel:+.1f}')
mac('StartsRatioTh', f"{float(th['starts'])/float(base['Hybrid']['starts']):.0f}")

# paired tests
with open(os.path.join(T, 'paired_tests.csv')) as f:
    for r in csv.DictReader(f):
        a, b = r['A'].title().replace('Mpc', 'Mpc'), r['B'].title()
        met = {'daily_cost': 'Cost', 'daily_Kh': 'Kh', 'daily_E': 'E'}[r['metric']]
        nm = f"Pair{alpha(r['A'])}{alpha(r['B'])}{met}"
        mac(nm, fmt(r['annual_diff'], 0))
        mac(nm + 'Lo', fmt(r['ci_lo'], 0)); mac(nm + 'Hi', fmt(r['ci_hi'], 0))
        p = float(r['wilcoxon_p'])
        mac(nm + 'P', '<0.001' if p < 1e-3 else f'{p:.3f}')

# sensitivity
with open(os.path.join(T, 'sensitivity.csv')) as f:
    for r in csv.DictReader(f):
        s = SCN.get(r['scenario']); k = KEY[r['controller']]
        if s is None: continue
        for col, nm, d in (('E_total', 'E', 0), ('cost', 'Cost', 0), ('Kh_total', 'Kh', 0), ('accept_pct', 'Acc', 1),
                           ('CO2_mean', 'Co', 0), ('h_CO2_1000', 'CoH', 0), ('PM_mean', 'Pm', 1),
                           ('d_PM_15', 'PmD', 0), ('d_PM_60', 'PmDsixty', 0), ('h_RH_over', 'Rh', 0),
                           ('peak_share', 'PkSh', 3)):
            mac(f'S{s}{nm}{k}', fmt(r[col], d))

# uncertainty analysis
uq = os.path.join(T, 'uq_summary.csv')
if os.path.exists(uq):
    rows = [l.strip().split(',') for l in open(uq)]
    for r in rows:
        if r[0] == 'samples': mac('UqN', r[1])
        elif r[0] in ('PID','E-MPC','DQN','Hybrid'):
            k = KEY[r[0]]; mac(f'UqBestCost{k}', r[1]); mac(f'UqBestKh{k}', r[2])
        elif r[0].startswith('hybrid_vs_pid_cost'): mac('UqHPcostLo', r[1]); mac('UqHPcostMed', r[2]); mac('UqHPcostHi', r[3])
        elif r[0].startswith('hybrid_vs_pid_Kh'): mac('UqHPkhLo', r[1]); mac('UqHPkhMed', r[2]); mac('UqHPkhHi', r[3])
        elif r[0].startswith('hybrid_vs_mpc_cost'): mac('UqHMcostLo', r[1]); mac('UqHMcostMed', r[2]); mac('UqHMcostHi', r[3])
        elif r[0].startswith('hybrid_vs_mpc_Kh'): mac('UqHMkhLo', r[1]); mac('UqHMkhMed', r[2]); mac('UqHMkhHi', r[3])
        elif r[0] == 'hybrid_dominates_pid_share': mac('UqDomHP', f'{100*float(r[1]):.0f}')
        elif r[0] == 'hybrid_dominates_mpc_share': mac('UqDomHM', f'{100*float(r[1]):.0f}')
        elif r[0] == 'thermostat_cheapest_share': mac('UqThCheap', f'{100*float(r[1]):.0f}')
        elif r[0] == 'thermostat_worst_discomfort_share': mac('UqThWorst', f'{100*float(r[1]):.0f}')

with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print(f'wrote {len(lines)-1} macros to {OUT}')
for c in COPIES:
    if os.path.isdir(os.path.dirname(c)):
        with open(c, 'w') as f:
            f.write('\n'.join(lines) + '\n')
        print(f'copied to {c}')

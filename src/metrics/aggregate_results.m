function A = aggregate_results(cfg)
%AGGREGATE_RESULTS  Collect run KPIs, compute seed statistics and paired tests, write tables.
rd = fullfile(cfg.out_dir, 'runs'); td = fullfile(cfg.out_dir, 'tables');
if ~exist(td, 'dir'), mkdir(td); end
C = cfg.controllers; L = cfg.labels; nc = numel(C); seeds = cfg.seeds;
kp = {'E_total','E_vrf','cost','Kh_over','Kh_under_hvac','Kh_total','accept_pct','rmse_occ', ...
      'P_peak','peak_share','h_RH_over','starts','ctrl_ms','carbon'};
A.kp = kp;
%% ---------------- main results: mean and 95 % t-CI over seeds ----------------
M = nan(nc, numel(kp), numel(seeds));
for i = 1:nc
    for j = 1:numel(seeds)
        fn = fullfile(rd, sprintf('base__%s__s%d.mat', C{i}, seeds(j)));
        if ~exist(fn, 'file'), continue; end
        S = load(fn);
        S.K.carbon = S.K.E_total * cfg.grid_factor;          % always use the current factor
        for q = 1:numel(kp), M(i,q,j) = S.K.(kp{q}); end
    end
end
n  = sum(~isnan(M(:,1,:)), 3);
mu = nanmean_(M, 3); sd = nanstd_(M, 3);
tq = [12.706 4.303 3.182 2.776 2.571 2.447 2.365 2.306 2.262];
hw = zeros(size(mu));
for i = 1:nc, if n(i) > 1, hw(i,:) = tq(n(i)-1) * sd(i,:) / sqrt(n(i)); end, end
A.mean = mu; A.hw = hw; A.n = n; A.M = M;
fid = fopen(fullfile(td, 'main_kpis.csv'), 'w');
fprintf(fid, 'controller,n_seeds'); hdr = [kp; kp]; fprintf(fid, ',%s,%s_ci95', hdr{:}); fprintf(fid, '\n');
for i = 1:nc
    fprintf(fid, '%s,%d', L{i}, n(i));
    for q = 1:numel(kp), fprintf(fid, ',%.7g,%.4g', mu(i,q), hw(i,q)); end
    fprintf(fid, '\n');
end
fclose(fid);
% relative to thermostat
b = mu(1,:);
A.rel = 100*(mu - repmat(b, nc, 1)) ./ repmat(b, nc, 1);

%% ---------------- LaTeX main table ----------------
fid = fopen(fullfile(td, 'main_kpis.tex'), 'w');
fprintf(fid, '%% generated by aggregate_results.m -- mean +/- 95%% CI over %d seeds\n', max(n));
fprintf(fid, '\\begin{tabular}{lrrrrrrr}\n\\hline\n');
fprintf(fid, 'Controller & Energy (kWh) & Cost (INR) & $\\Delta$cost & Discomfort (K\\,h) & Acceptable (\\%%) & RMSE (K) & Peak (kW)\\\\\n\\hline\n');
for i = 1:nc
    fprintf(fid, '%s & %s & %s & %s & %s & %s & %s & %s\\\\\n', L{i}, pm(mu(i,1),hw(i,1),0), pm(mu(i,3),hw(i,3),0), ...
        rel_str(A.rel(i,3), i), pm(mu(i,6),hw(i,6),1), pm(mu(i,7),hw(i,7),1), pm(mu(i,8),hw(i,8),2), pm(mu(i,9),hw(i,9),2));
end
fprintf(fid, '\\hline\n\\end{tabular}\n'); fclose(fid);

%% ---------------- paired daily tests (seed 1) ----------------
pairs = {'hybrid','mpc'; 'hybrid','pid'; 'mpc','pid'; 'rl','pid'; 'pid','thermostat'; ...
         'mpc','thermostat'; 'rl','thermostat'; 'hybrid','thermostat'};
fid = fopen(fullfile(td, 'paired_tests.csv'), 'w');
fprintf(fid, 'A,B,metric,annual_diff,ci_lo,ci_hi,wilcoxon_p\n');
A.paired = {};
for r = 1:size(pairs,1)
    fa = fullfile(rd, sprintf('base__%s__s1.mat', pairs{r,1}));
    fb = fullfile(rd, sprintf('base__%s__s1.mat', pairs{r,2}));
    if ~exist(fa,'file') || ~exist(fb,'file'), continue; end
    Sa = load(fa); Sb = load(fb);
    for met = {'daily_cost','daily_Kh','daily_E'}
        P = paired_stats(Sa.K.(met{1}), Sb.K.(met{1}), 7, 2000, r);
        fprintf(fid, '%s,%s,%s,%.2f,%.2f,%.2f,%.3g\n', pairs{r,1}, pairs{r,2}, met{1}, P.diff, P.ci(1), P.ci(2), P.p);
        A.paired(end+1,:) = {pairs{r,1}, pairs{r,2}, met{1}, P}; %#ok<AGROW>
    end
end
fclose(fid);

%% ---------------- sensitivity / ablation (seed 1) ----------------
scen = {'base','heatwave','mass_low','mass_high','flat_tariff','no_mismatch','mpc_perfect', ...
        'horizon6','horizon12','rl_levels3','rl_levels9','rl_noshield','heat_perfect','heat_backoff1', ...
        'tariff_steep','tariff_msedcl','hyb_noPI','hyb_nosafety','iaq_nofilter','vent_humidity','vent_off'};
kq = {'E_total','cost','Kh_total','accept_pct','P_peak','peak_share','CO2_mean','h_CO2_1000','PM_mean','d_PM_15','d_PM_60','h_RH_over'};
fid = fopen(fullfile(td, 'sensitivity.csv'), 'w');
fprintf(fid, 'scenario,controller'); fprintf(fid, ',%s', kq{:}); fprintf(fid, '\n');
A.sens = struct();
for s = 1:numel(scen)
    for i = 1:nc
        fn = fullfile(rd, sprintf('%s__%s__s1.mat', scen{s}, C{i}));
        if ~exist(fn, 'file'), continue; end
        S = load(fn);
        fprintf(fid, '%s,%s', scen{s}, L{i});
        for q = 1:numel(kq), fprintf(fid, ',%.7g', S.K.(kq{q})); end
        fprintf(fid, '\n');
        A.sens.(scen{s}).(C{i}) = S.K;
    end
end
fclose(fid);
save(fullfile(cfg.out_dir, 'aggregate.mat'), 'A', '-v7');
end

function s = pm(m, h, d)
f = sprintf('%%.%df', d);
if h > 0, s = sprintf([f ' $\\pm$ ' f], m, h); else, s = sprintf(f, m); end
end
function s = rel_str(r, i)
if i == 1, s = '--'; else, s = sprintf('%+.1f\\%%', r); end
end
function m = nanmean_(x, d)
k = ~isnan(x); x(~k) = 0; m = sum(x, d) ./ max(1, sum(k, d));
end
function s = nanstd_(x, d)
m = nanmean_(x, d); k = ~isnan(x); r = x - repmat(m, [1 1 size(x,3)]); r(~k) = 0;
s = sqrt(sum(r.^2, d) ./ max(1, sum(k, d) - 1));
end

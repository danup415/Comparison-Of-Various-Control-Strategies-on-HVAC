function write_summary(cfg, A)
%WRITE_SUMMARY  Human-readable results summary (results/summary.md).
fid = fopen(fullfile(cfg.out_dir, 'summary.md'), 'w');
L = cfg.labels; nc = numel(L); kp = A.kp;
g = @(name) find(strcmp(kp, name));
fprintf(fid, '# Results summary (generated by run_all.m)\n\n');
fprintf(fid, 'Main study: full TMY year (ISHRAE Pune), 15-min steps, mean +/- 95%% CI over %d seeds.\n\n', max(A.n));
fprintf(fid, '| Controller | Energy (kWh) | Cost (INR) | Cost vs thermostat | Discomfort (K h) | Acceptable (%%) | RMSE occ. (K) | Peak (kW) | VRF energy in peak hours (%%) | Compressor starts |\n');
fprintf(fid, '|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for i = 1:nc
    fprintf(fid, '| %s | %.0f ± %.0f | %.0f ± %.0f | %+.1f%% | %.0f ± %.0f | %.1f ± %.1f | %.2f | %.2f | %.1f | %.0f |\n', L{i}, ...
        A.mean(i,g('E_total')), A.hw(i,g('E_total')), A.mean(i,g('cost')), A.hw(i,g('cost')), A.rel(i,g('cost')), ...
        A.mean(i,g('Kh_total')), A.hw(i,g('Kh_total')), A.mean(i,g('accept_pct')), A.hw(i,g('accept_pct')), ...
        A.mean(i,g('rmse_occ')), A.mean(i,g('P_peak')), 100*A.mean(i,g('peak_share')), A.mean(i,g('starts')));
end
fprintf(fid, '\n## Paired daily tests (seed 1, 7-day block bootstrap 95%% CI, Wilcoxon signed-rank)\n\n');
fprintf(fid, '| A vs B | Metric | Annual difference A-B | 95%% CI | p |\n|---|---|---:|---|---:|\n');
for r = 1:size(A.paired,1)
    P = A.paired{r,4};
    fprintf(fid, '| %s vs %s | %s | %.1f | [%.1f, %.1f] | %.2g |\n', A.paired{r,1}, A.paired{r,2}, A.paired{r,3}, P.diff, P.ci(1), P.ci(2), P.p);
end
fprintf(fid, '\n## Sensitivity and ablations (seed 1)\n\n| Scenario | Controller | Energy (kWh) | Cost (INR) | Discomfort (K h) | Acceptable (%%) | CO2 mean (ppm) | PM2.5 mean (ug/m3) | days PM2.5 > 15 | days > 60 |\n|---|---|---:|---:|---:|---:|---:|---:|---:|---:|\n');
sc = fieldnames(A.sens);
for s = 1:numel(sc)
    cc = fieldnames(A.sens.(sc{s}));
    for i = 1:numel(cc)
        K = A.sens.(sc{s}).(cc{i}); lab = L{strcmp(cfg.controllers, cc{i})};
        fprintf(fid, '| %s | %s | %.0f | %.0f | %.0f | %.1f | %.0f | %.1f | %d | %d |\n', sc{s}, lab, K.E_total, K.cost, K.Kh_total, K.accept_pct, K.CO2_mean, K.PM_mean, K.d_PM_15, K.d_PM_60);
    end
end
fclose(fid);
end
